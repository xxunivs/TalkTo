"""잊었다는 말 — 고인 대화 상대는 잊었다·기억이 안 난다고 하지 않는다(잠금).

이 말이 든 고친 말투 예시(corrections.style_examples)와 만들 때 질문 M8-08 '모르는 걸 물으면'
답(intake.build_intake)은 고인 대화 상대에게 보내지 않는다(말버릇으로 따라 하지 않게). 살아 계신
분은 그대로다.

잡는 말: 기억이 (잘) 안 나·기억이 나지 않·기억을 못 하·생각이 (잘) 안 나·생각이 나지 않·까먹·
잊어버·잊어먹·잊었·잊혀·가물가물·가물거려·기억에 없다·깜빡했다·다 잊어서.
잡지 않는 말(잊지 말라는 당부·잊지 않았다는 말): 잊지 마라·까먹지 말고·잊어버리면 안 돼·
안 까먹었다·못 잊어·잊혀지지 않는다·잊어버린 적 없다·네 생각이 안 나는 날이 없다·다 잊어버려라.
'모르겠다'는 잊은 말이 아니라 넣지 않는다(M8-08 은 바로 그 말을 묻는다).
"""

import re

# 기억이 '하나도'·'통'·'이젠 잘' 안 나(꾸밈말 둘까지)
_ADV = (
    r"(?:(?:잘|하나도|전혀|통|도통|도무지|영|당최|별로|이젠|이제는|이제|요즘|요새|다|잘은)\s?)"
    r"{0,2}"
)
# 기억·생각이 안 난다. 뒤가 '…는 날이 없다'면 늘 떠오른다는 말이라 뺀다
_NO_RECALL = (
    r"(?:기억|생각)(?:이|도|은|조차)?\s?" + _ADV + r"(?:안\s?[나났난날납]|나[지질진][가는도]?\s?않)"
    r"(?!는?\s?(?:날|때|적)\S{0,2}\s?없)"
)
_CANNOT = r"기억(?:을|도|은|조차)?\s?" + _ADV + r"못\s?[하해했한할합]"
_STEMS = r"(?:까먹|잊어\s?버|잊어\s?먹|잊었|잊[혀혔])"
# 앞에 '안'·'못'이 따로 붙으면 잊지 않았다는 말(안 까먹었다·못 잊어. '그동안'의 '안'은 아니다)
_NOT_BEFORE = r"(?<!(?<![가-힣])[안못]\s)(?<!(?<![가-힣])[안못])"
# 뒤가 당부·부정이면 잊은 말이 아니다: 까먹지 마라·잊어버리지 말고·잊혀지지 않는다 /
# 잊어버리면 안 돼 / 잊어버린 적 없다 / 다 잊어버려라·까먹을라
_NOT_AFTER = (
    r"(?![가-힣]{0,2}[지진질][는도를가]?\s?(?:마(?:[라요세시]|(?![가-힣]))|말[고아라거자도게]|않)"
    r"|[가-힣]{0,3}(?:면|서는|선)\s?안\s?[돼되된]"
    r"|[가-힣]{0,3}\s?적[이은도]?\s?없"
    r"|[가-힣]?(?:라|렴|거라|세요)(?![가-힣]))"
)
# 기억에 없다·기억이 없어('기억에 없는 일'·'기억에 없으면'처럼 꾸미거나 조건인 말은 아니다) /
# 깜빡했다 / 다 잊어서·다 잊은 / 가물거린다
_OTHER = r"기억(?:에|이)\s?없(?!는|으면|다면)|깜[빡박]\s?했|다\s?잊(?:어서|은)|가물\s?(?:가물|거)"
FORGOT = re.compile(rf"{_NO_RECALL}|{_CANNOT}|{_NOT_BEFORE}{_STEMS}{_NOT_AFTER}|{_OTHER}")


def says_forgot(text: str | None) -> bool:
    """잊었다·기억이 안 난다는 말이 들었는지."""
    return bool(text) and FORGOT.search(str(text)) is not None
