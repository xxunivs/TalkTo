from __future__ import annotations

LOW_MEMORY_MAX = 5      # 이 수 이하면 '기억이 적다'. 실측 전 임시값(4층 레포 10/18 fix_low_memory 3절).
BE_MEMORY_TOP_K = 5     # BE 가 /responses 에 보내는 검색 기억 수(지금 top-5).
LOW_MEMORY_HEAD = "# 기억이 아직 적을 때"


def memory_count(n_sent: int, memory_total: int | None = None, *, top_k: int = BE_MEMORY_TOP_K) -> int | None:
    """총 기억 수. 모르면 None(= 적다고 보지 않는다)."""
    if memory_total is not None:
        return memory_total
    if n_sent < top_k:
        return n_sent
    return None


def is_low_memory(n_sent: int, memory_total: int | None = None, *, low_max: int = LOW_MEMORY_MAX,
                  top_k: int = BE_MEMORY_TOP_K) -> bool:
    n = memory_count(n_sent, memory_total, top_k=top_k)
    return n is not None and n <= low_max


